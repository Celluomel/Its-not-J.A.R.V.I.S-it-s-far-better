  mkdirSync('test-results', { recursive: true });
  const browser = await chromium.launch({ headless: true, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream'] });
  const page = await browser.newPage({ viewport: { width: 1600, height: 1000 }, reducedMotion: 'no-preference' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const snapshot = { version: 1, ready: true, busy: false, timestamp: Date.now()/1000, uptime: 180, cycle: 9, engines: { persona: true, organism: true, loop: true }, providers: { stt: 'whisper', tts: 'pyttsx3' }, timings: { first_token_ms: 214, turn_ms: 820 }, events: [{ id: 'e1', label: 'Turn completed', timestamp: Date.now()/1000, turn_id: 'test-turn' }] };
