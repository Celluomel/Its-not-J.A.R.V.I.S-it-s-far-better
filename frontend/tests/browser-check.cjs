  await page.getByRole('button', {name:'Send message', exact:true}).click();
  await page.getByText('We discussed how memory should distinguish facts from interpretation.', { exact:true }).waitFor();
  await page.waitForTimeout(1700);
  const canvas = page.locator('canvas');
  assert.equal(await canvas.count(), 1);
  const before = PNG.sync.read(await canvas.screenshot());
  let illuminated = 0;
  for (let i = 0; i < before.data.length; i += 4) if (Math.max(before.data[i], before.data[i+1], before.data[i+2]) > 65) illuminated++;
  assert(illuminated > 1000, `Canvas is blank or too dim: ${illuminated}`);
  await page.waitForTimeout(500);
  const after = PNG.sync.read(await canvas.screenshot());
  let changed = 0;
  for (let i = 0; i < before.data.length; i += 4) if (Math.abs(before.data[i]-after.data[i]) + Math.abs(before.data[i+1]-after.data[i+1]) > 5) changed++;
  assert(changed > 100, `Organism is not moving: ${changed}`);
  await page.screenshot({ path:'test-results/desktop-chat.png' });
  await page.getByRole('button', {name:'Open cognitive inspector',exact:true}).click();
  await page.getByRole('heading', {name:'Cognition',exact:true}).waitFor();
  const chatRect = await page.locator('.conversation').boundingBox();
  const inspectorRect = await page.locator('.inspector').boundingBox();
  assert(chatRect.x + chatRect.width <= inspectorRect.x + 1, 'Desktop inspector overlaps chat');
  await page.getByRole('tab',{name:'Diagnostics'}).click();
  await page.getByText('214 ms', {exact:true}).waitFor();
  await page.getByRole('tab',{name:'Overview'}).click();
  await page.screenshot({ path:'test-results/desktop-inspector.png' });
  await page.setViewportSize({width:1100,height:900});
  const narrowChat = await page.locator('.conversation').boundingBox();
  const narrowInspector = await page.locator('.inspector').boundingBox();
  assert(narrowChat.x+narrowChat.width <= narrowInspector.x+1, 'Narrow desktop inspector overlaps chat');
