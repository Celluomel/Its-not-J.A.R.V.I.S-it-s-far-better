  await page.waitForTimeout(1000);
  await page.screenshot({path:'test-results/desktop-voice.png'});
  await page.getByRole('button',{name:'End voice mode',exact:true}).click();
  let capturedWav = false;
  await page.route('**/api/interface/transcribe', route => {
    const bytes = route.request().postDataBuffer();
    capturedWav = bytes.length > 44 && bytes.subarray(0,4).toString() === 'RIFF' && bytes.subarray(8,12).toString() === 'WAVE';
    return route.fulfill({json:{text:'Voice capture test'}});
  });
  await page.getByRole('button',{name:'Record voice message',exact:true}).click();
  await page.getByRole('button',{name:'Finish recording',exact:true}).waitFor();
  await page.waitForTimeout(300);
  await page.getByRole('button',{name:'Finish recording',exact:true}).click();
  await page.waitForFunction(() => document.querySelector('textarea').value === 'Voice capture test');
  assert(capturedWav, 'Microphone capture did not produce WAV');
  await page.reload();
  await page.getByText('We discussed how memory should distinguish facts from interpretation.', {exact:true}).waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(700);
