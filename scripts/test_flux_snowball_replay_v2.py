"""
test_flux_snowball_replay_v2.py — Phase 6.9
==============================================
Extends test_flux_snowball_replay.py (v100) with the ten curves requested
and, most importantly, THE DECISIVE TEST: does a Flux-driven perturbation
remain encoded in memory + goals + predictive model + self-model AFTER
Flux is cut off, or does the trajectory immediately snap back? Persistence
after removal is the actual evidence for an internalized, self-propagating
trajectory change — not just live external influence while Flux is
talking.

Design: Flux is ON for cycles [1, cutoff], then OFF for (cutoff, N]. If
divergence (any dimension) collapses to ~0 quickly after cutoff, the
perturbation was live-only. If it persists — even partially — above the
pre-Flux baseline, that's the real finding.

Honest scope — read before trusting the numbers
---------------------------------------------------
Two modes, run separately, both real:

  1. STATISTICAL mode (default, N large e.g. 300): response text for
     both trajectories is generated by a small deterministic template
     library (same honesty policy as v100) — NOT a real LLM. Gives the
     large-N statistical shape but the prediction-error/self-model/
     memory numbers it produces are only as good as those templates.

  2. HIGH-FIDELITY mode (--llm-authored, small N e.g. 15-20): response
     text for EVERY cycle, both trajectories, is hand-authored inline in
     this file by Claude actually acting as the response generator (in
     place of Qwen2.5-7B, per the user's explicit request) — real
     generated content, not templates. Small N because this doesn't
     scale to hundreds of cycles by hand. This is what actually validates
     that the statistical mode's templates aren't producing an artifact.

Metrics 4-7 (prediction error, memory-state, self-model, decision/action)
only have real content to measure BECAUSE this version generates actual
response text each cycle (v100 never did — deliberate() only ever picked
a workspace focus, not a full reply). Metrics 8-10 (entropy, Flux
contribution, recovery time) are computed directly from real workspace/
competition state, no generation needed.
"""
