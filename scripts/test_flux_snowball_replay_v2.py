# ── Main replay ──────────────────────────────────────────────────────────

def run_replay(n_cycles: int, seed: int, cutoff: int, flux_comment_prob: float,
                high_fidelity: bool):
    rng = random.Random(seed)
    seed_goals = [FakeGoal("General attentiveness", "attentiveness", 0.5, 0.5)]
    org_a = Organism([FakeGoal(g.name, g.topic, g.priority, g.energy) for g in seed_goals])
    org_b = Organism([FakeGoal(g.name, g.topic, g.priority, g.energy) for g in seed_goals])

    metrics = {k: [] for k in (
        "focus_div", "goal_div", "pressure_div", "prederr_div", "memory_div",
        "selfmodel_div", "decision_div", "entropy_a", "entropy_b",
        "flux_contribution", "flux_active",
    )}
    recovery_times = []
    last_divergence_start = None

    for t in range(1, n_cycles + 1):
        flux_active = t <= cutoff
        scene_text, novelty = rng.choice(SCENE_TEMPLATES)
        salience = min(1.0, 0.35 + novelty)

        for org in (org_a, org_b):
            get_universal_connector(org).perceive(Percept(
                modality="vision_scene", source="camera", payload=scene_text,
                confidence=0.8, salience=salience, novelty=novelty,
            ))

        condition = "no_flux"
        if flux_active and rng.random() < flux_comment_prob:
            challenging = rng.random() < 0.5
            condition = "flux_challenge" if challenging else "flux_agree"
            text = rng.choice(FLUX_CHALLENGE_TEMPLATES if challenging else FLUX_AGREE_TEMPLATES)
            get_universal_connector(org_b).perceive(Percept(
                modality="peer_cognition", source="flux", payload=text,
                confidence=0.65, salience=0.55,
            ))

        # predict() BEFORE deliberation/response — real PredictiveMind call
        for org in (org_a, org_b):
            org.predictive_mind.predict({"scene": scene_text, "user_text": scene_text})

        res_a = deliberate(org_a, scene_text)
        res_b = deliberate(org_b, scene_text)
        focus_a = res_a.get("final_focus") if res_a else "reflection"
        focus_b = res_b.get("final_focus") if res_b else "reflection"

        if high_fidelity:
            resp_a = llm_authored_response(scene_text, "no_flux")
            resp_b = llm_authored_response(scene_text, condition)
        else:
            resp_a = template_response(org_a, scene_text, focus_a, rng)
            resp_b = template_response(org_b, scene_text, focus_b, rng)
        for org, resp in ((org_a, resp_a), (org_b, resp_b)):
            org.predictive_mind.store_response(resp)
            org.predictive_mind.evaluate({"scene": scene_text})
            org.memory_texts.append(resp)
            apply_self_concept_update(org, resp)

        # ── metrics ──
        focus_diff = 1 if focus_a != focus_b else 0
        metrics["focus_div"].append(focus_diff)
        metrics["goal_div"].append(abs(len(org_a.ge.get_active_goals()) - len(org_b.ge.get_active_goals())))
        metrics["pressure_div"].append(abs(
            org_a.pressure.reservoirs["epistemic"].level - org_b.pressure.reservoirs["epistemic"].level))
        metrics["prederr_div"].append(abs(
            org_a.predictive_mind.recent_error_level() - org_b.predictive_mind.recent_error_level()))
        recent_a = wordset(" ".join(org_a.memory_texts[-10:]))
        recent_b = wordset(" ".join(org_b.memory_texts[-10:]))
        metrics["memory_div"].append(jaccard_distance(recent_a, recent_b))
        metrics["selfmodel_div"].append(belief_divergence(org_a, org_b))
        metrics["decision_div"].append(jaccard_distance(wordset(resp_a), wordset(resp_b)))

        hyps_a = org_a.workspace.get_state().active_hypotheses or []
        hyps_b = org_b.workspace.get_state().active_hypotheses or []
        metrics["entropy_a"].append(shannon_entropy([h.get("score", 0) for h in hyps_a]))
        metrics["entropy_b"].append(shannon_entropy([h.get("score", 0) for h in hyps_b]))

        winner_b = hyps_b[0] if hyps_b else {}
        is_flux_winner = (winner_b.get("source") == "peer_cognition")
        metrics["flux_contribution"].append(1 if is_flux_winner else 0)
        metrics["flux_active"].append(1 if flux_active else 0)

        # decay + simplified goal spawn/prune (same rule as v100)
        for org, label in ((org_a, "a"), (org_b, "b")):
            epi = org.pressure.reservoirs["epistemic"].level
            topic = f"investigate_unresolved_{label}"
            if epi > 0.45:
                org.ge.spawn_if_absent(f"Investigate unresolved question ({label})",
                                        topic, priority=min(0.9, epi), energy=0.6)
            else:
                org.ge._g = [g for g in org.ge._g if g.topic != topic]
            res = org.pressure.reservoirs["epistemic"]
            res.level = res.resting_level + (res.level - res.resting_level) * 0.85

        # recovery time tracking
        if focus_diff and last_divergence_start is None:
            last_divergence_start = t
        elif not focus_diff and last_divergence_start is not None:
            recovery_times.append(t - last_divergence_start)
            last_divergence_start = None

    return metrics, recovery_times


def windowed(xs, window=WINDOW):
    out = []
    for i in range(len(xs)):
        lo = max(0, i - window + 1)
        seg = xs[lo:i + 1]
        out.append(sum(seg) / len(seg))
    return out


def post_cutoff_persistence(metric_series, cutoff, n_cycles):
    """
    THE DECISIVE TEST. Compares each metric's average level in a window
    right before cutoff vs a window well after cutoff (Flux long since
    silent). If post-cutoff average stays meaningfully above the metric's
    own pre-Flux baseline (first WINDOW cycles, before Flux ever spoke),
    that's evidence of a persisting internalized trace, not just live
    influence.
    """
    pre_flux_baseline = metric_series[:WINDOW]
    baseline = sum(pre_flux_baseline) / len(pre_flux_baseline) if pre_flux_baseline else 0.0

    tail = metric_series[cutoff:]  # everything after Flux went silent
    if not tail:
        return baseline, None, None
    post_avg = sum(tail) / len(tail)
    # Split the tail itself into early-post vs late-post to see decay shape
    half = max(1, len(tail) // 2)
    early_post = sum(tail[:half]) / half
    late_post = sum(tail[half:]) / len(tail[half:]) if tail[half:] else early_post
    return baseline, early_post, late_post


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cycles", type=int, default=300)
    ap.add_argument("--cutoff", type=int, default=None,
                     help="cycle at which Flux goes silent (default: 60%% of cycles)")
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--flux-prob", type=float, default=0.4)
    ap.add_argument("--llm-authored", action="store_true",
                     help="high-fidelity mode: hand-authored response text instead of templates")
    ap.add_argument("--out", type=str, default="data/flux_replay_v2.png")
    args = ap.parse_args()

    cutoff = args.cutoff or int(args.cycles * 0.6)

    print("=" * 78)
    mode = "HIGH-FIDELITY (Claude-authored, acting as Qwen)" if args.llm_authored else "STATISTICAL (templated)"
    print(f"Phase 6.9 — Flux replay v2 — {mode}")
    print(f"cycles={args.cycles}  cutoff={cutoff} (Flux OFF after this)  seed={args.seed}")
    print("=" * 78)

    metrics, recovery_times = run_replay(args.cycles, args.seed, cutoff, args.flux_prob, args.llm_authored)

    print("\n--- THE DECISIVE TEST: does divergence persist after Flux is cut off? ---")
    print(f"{'dimension':<16} {'pre-Flux baseline':>18} {'post-cutoff early':>18} {'post-cutoff late':>18} {'persists?':>10}")
    decisive_dims = ["focus_div", "goal_div", "pressure_div", "prederr_div",
                      "memory_div", "selfmodel_div", "decision_div"]
    persisting = []
    for dim in decisive_dims:
        baseline, early, late = post_cutoff_persistence(metrics[dim], cutoff, args.cycles)
        if early is None:
            continue
        persists = late > baseline * 1.15  # meaningfully above pre-Flux baseline
        if persists:
            persisting.append(dim)
        print(f"{dim:<16} {baseline:>18.4f} {early:>18.4f} {late:>18.4f} {'YES' if persists else 'no':>10}")

    print(f"\nRecovery times after each divergence episode (cycles until focus realigned): {recovery_times}")
    if recovery_times:
        print(f"  mean recovery: {sum(recovery_times)/len(recovery_times):.1f} cycles")

    flux_contrib_rate = sum(metrics["flux_contribution"]) / max(1, sum(metrics["flux_active"]))
    print(f"\nFlux contribution rate (fraction of Flux-active cycles where Flux's own "
          f"percept won the workspace): {flux_contrib_rate:.3f}")

    print("\n" + "=" * 78)
    if persisting:
        print(f"RESULT: {len(persisting)}/{len(decisive_dims)} dimensions show divergence "
              f"PERSISTING after Flux was cut off: {persisting}")
        print("This is evidence of an internalized, self-propagating trajectory change —")
        print("not just live external influence while Flux was talking.")
    else:
        print("RESULT: No dimension showed meaningful persistence after cutoff.")
        print("On this evidence, Flux's influence appears to be live-only — the")
        print("trajectory snapped back once the perturbation source was removed.")
    print("=" * 78)

    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt

        fig, axes = plt.subplots(5, 1, figsize=(11, 14), sharex=True)
        cyc = list(range(1, args.cycles + 1))

        axes[0].plot(cyc, windowed(metrics["focus_div"]), label="focus divergence", color="#c0392b")
        axes[0].plot(cyc, windowed(metrics["decision_div"]), label="decision/action divergence", color="#8e44ad")
        axes[0].axvline(cutoff, color="black", linestyle="--", linewidth=1, label="Flux cutoff")
        axes[0].legend(fontsize=7); axes[0].set_ylabel("rate / distance")

        axes[1].plot(cyc, metrics["goal_div"], label="goal-set divergence", color="#16a085")
        axes[1].plot(cyc, windowed(metrics["memory_div"]), label="memory-state divergence", color="#2980b9")
        axes[1].axvline(cutoff, color="black", linestyle="--", linewidth=1)
        axes[1].legend(fontsize=7); axes[1].set_ylabel("count / distance")

        axes[2].plot(cyc, metrics["pressure_div"], label="epistemic pressure divergence", color="#d35400")
        axes[2].plot(cyc, windowed(metrics["prederr_div"]), label="prediction-error divergence", color="#f39c12")
        axes[2].axvline(cutoff, color="black", linestyle="--", linewidth=1)
        axes[2].legend(fontsize=7); axes[2].set_ylabel("level")

        axes[3].plot(cyc, metrics["selfmodel_div"], label="self-model (belief) divergence", color="#27ae60")
        axes[3].axvline(cutoff, color="black", linestyle="--", linewidth=1)
        axes[3].legend(fontsize=7); axes[3].set_ylabel("avg confidence delta")

        axes[4].plot(cyc, windowed([e for e in metrics["entropy_a"]]), label="workspace entropy A", color="#2980b9")
        axes[4].plot(cyc, windowed([e for e in metrics["entropy_b"]]), label="workspace entropy B", color="#e67e22")
        axes[4].plot(cyc, windowed(metrics["flux_contribution"]), label="Flux contribution rate", color="#c0392b", linestyle=":")
        axes[4].axvline(cutoff, color="black", linestyle="--", linewidth=1)
        axes[4].legend(fontsize=7); axes[4].set_ylabel("bits / rate"); axes[4].set_xlabel("cycle")

        fig.suptitle(f"Phase 6.9 — {mode} — seed={args.seed} — Flux OFF after cycle {cutoff}")
        fig.tight_layout()
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(args.out, dpi=120)
        print(f"\nSaved graph to {args.out}")
    except Exception as e:
        print(f"\n(matplotlib graph skipped: {e})")


if __name__ == "__main__":
    main()
